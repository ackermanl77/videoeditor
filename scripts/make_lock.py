"""Write requirements-lock.txt: the exact versions a clean install of
requirements-build.txt resolves to, with this interpreter's Python version.

    python scripts/make_lock.py

It installs into a throwaway venv (nothing in your own environment changes),
then freezes it. Release builds and the integration CI job install with
`-c requirements-lock.txt`; regenerate it deliberately when raising a bound.
"""
from __future__ import annotations

import platform
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> int:
    with tempfile.TemporaryDirectory(prefix="video-editor-lock-") as tmp:
        venv = Path(tmp) / "venv"
        subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True)
        python = venv / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
        subprocess.run([str(python), "-m", "pip", "install", "-q", "--disable-pip-version-check", "-r", str(ROOT / "requirements-build.txt")], check=True)
        frozen = subprocess.run([str(python), "-m", "pip", "freeze", "--all", "--disable-pip-version-check"], check=True, capture_output=True, text=True).stdout
    pins = sorted((line for line in frozen.splitlines() if line and not line.lower().startswith(("pip==", "setuptools==", "wheel=="))), key=str.lower)
    header = [
        "# Generated by scripts/make_lock.py -- do not edit by hand.",
        f"# Python {platform.python_version()} on {sys.platform}: a clean install of requirements-build.txt.",
        "#   pip install -r requirements-build.txt -c requirements-lock.txt",
    ]
    (ROOT / "requirements-lock.txt").write_text("\n".join(header + pins) + "\n", encoding="utf-8")
    print(f"wrote {len(pins)} pins to requirements-lock.txt")
    return 0


if __name__ == "__main__":
    sys.exit(main())
